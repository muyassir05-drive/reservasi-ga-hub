-- Run this in Supabase SQL Editor before deploying the website.
create extension if not exists pgcrypto;
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  employee_id text unique not null,
  full_name text not null,
  role text not null default 'employee' check (role in ('admin','employee')),
  area text not null default 'Jakarta' check (area in ('Jakarta','Semarang','Yogyakarta','Bali')),
  created_at timestamptz not null default now()
);
create table if not exists public.vehicles (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  plate text not null,
  driver_name text,
  color text,
  location text not null default 'Jakarta',
  parity text check (parity in ('Ganjil','Genap')),
  status text not null default 'Available' check (status in ('Available','Maintenance','Inactive')),
  notes text,
  created_at timestamptz not null default now()
);
create table if not exists public.reservations (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id),
  employee_id text not null,
  employee_name text not null,
  area text not null check (area in ('Jakarta','Semarang','Yogyakarta','Bali')),
  date date not null,
  start_time time not null,
  end_time time not null,
  vehicle_id uuid not null references public.vehicles(id),
  purpose text not null,
  status text not null default 'Pending' check (status in ('Pending','Approved','Rejected','Cancelled','Completed')),
  created_at timestamptz not null default now(),
  approved_by uuid references public.profiles(id),
  constraint valid_time_range check (start_time < end_time)
);
create index if not exists reservations_date_vehicle_idx on public.reservations(date, vehicle_id, start_time, end_time);
create index if not exists reservations_user_idx on public.reservations(user_id, created_at desc);

create or replace function public.is_ga_admin()
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles p where p.id = auth.uid() and p.role = 'admin'); $$;
revoke all on function public.is_ga_admin() from public;
grant execute on function public.is_ga_admin() to authenticated;

alter table public.profiles enable row level security;
alter table public.vehicles enable row level security;
alter table public.reservations enable row level security;

drop policy if exists "profiles self or admin read" on public.profiles;
create policy "profiles self or admin read" on public.profiles for select to authenticated using (id = auth.uid() or public.is_ga_admin());
drop policy if exists "admin manage profiles" on public.profiles;
create policy "admin manage profiles" on public.profiles for all to authenticated using (public.is_ga_admin()) with check (public.is_ga_admin());

drop policy if exists "authenticated read vehicles" on public.vehicles;
create policy "authenticated read vehicles" on public.vehicles for select to authenticated using (true);
drop policy if exists "admin manage vehicles" on public.vehicles;
create policy "admin manage vehicles" on public.vehicles for all to authenticated using (public.is_ga_admin()) with check (public.is_ga_admin());

drop policy if exists "employee reads own reservations admin reads all" on public.reservations;
create policy "employee reads own reservations admin reads all" on public.reservations for select to authenticated using (user_id = auth.uid() or public.is_ga_admin());
drop policy if exists "employee creates own reservation" on public.reservations;
create policy "employee creates own reservation" on public.reservations for insert to authenticated with check (user_id = auth.uid() and status = 'Pending');
drop policy if exists "admin updates reservations" on public.reservations;
create policy "admin updates reservations" on public.reservations for update to authenticated using (public.is_ga_admin()) with check (public.is_ga_admin());

